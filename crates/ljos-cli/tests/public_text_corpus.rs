#[test]
fn every_leak_in_the_table_is_refused() {
    let screen = Screen::default();
    let kept: Vec<String> = LEAKS
        .iter()
        .filter(|(_, text)| classify(text, &screen).is_none())
        .map(|(group, text)| format!("{group}: {text:?}"))
        .collect();
    assert!(
        kept.is_empty(),
        "{} of {} leaks were not refused:\n{}",
        kept.len(),
        LEAKS.len(),
        kept.join("\n")
    );
}

#[test]
fn every_ordinary_string_in_the_table_passes() {
    let screen = Screen::default();
    let refused: Vec<String> = BENIGN
        .iter()
        .filter_map(|text| {
            classify(text, &screen).map(|class| format!("{}: {text:?}", class.name()))
        })
        .collect();
    assert!(
        refused.is_empty(),
        "{} of {} ordinary strings were refused:\n{}",
        refused.len(),
        BENIGN.len(),
        refused.join("\n")
    );
}
